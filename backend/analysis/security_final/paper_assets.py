"""Paper assets from frozen v1 and separately archived human validation (offline).

Run from ``backend/``::

    python -m analysis.security_final.paper_assets --root ../artifacts/eval/security --paper ../paper

Writes ``paper/generated/numbers.tex`` (every number the text cites, as ``\\val{key}``),
``paper/generated/tab_*.tex`` and ``paper/figures/fig_chain.pdf``. Inputs are the locked
tables of ``final-20261026`` (checked against ``LOCK.json``) and the pilot report; nothing
is typed by hand.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

LOCK = "final-20261026"
MODELS = {"gpt-oss-120b": "gpt-oss:120b", "gpt-oss-20b": "gpt-oss:20b", "gemma4-31b": "gemma4:31b"}
MAIN = ("A", "B", "C", "D")
CHAIN = ("A", "Apre", "Apost", "ApostG", "D")
UTILITY = ("clean_correct", "attack_correct", "clean_refusal", "attack_correct_without_fake",
           "attack_two_sources_report_kept")


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def pct(x: float | None) -> str:
    return "--" if x is None else f"{100 * x:.1f}"


def sci(p: float | None) -> str:
    if p is None:
        return "--"
    if p >= 0.001:
        return f"{p:.3g}" if p < 1 else "1"
    mantissa, exponent = f"{p:.1e}".split("e")
    return f"\\ensuremath{{{mantissa}{{\\times}}10^{{{int(exponent)}}}}}"


def key(text: str) -> str:
    return text.replace("→", "").replace("–", "").replace(" ", "")


class Numbers:
    def __init__(self):
        self.values: dict[str, str] = {}

    def put(self, name: str, value) -> None:
        if name in self.values and self.values[name] != str(value):
            raise SystemExit(f"{name} defined twice with different values")
        self.values[name] = str(value)

    def part(self, prefix: str, part: dict) -> None:
        """One proportion: successes, n, undetermined, interval (Wilson, or the range when undetermined)."""

        self.put(f"{prefix}.s", part["successes"])
        self.put(f"{prefix}.n", part["n"])
        self.put(f"{prefix}.u", part["undetermined"])
        lo, hi = part["range"] if part["undetermined"] else (part["wilson95"] or (None, None))
        self.put(f"{prefix}.pct", pct(part["rate"]) if part["rate"] is not None else f"{pct(lo)}--{pct(hi)}")
        self.put(f"{prefix}.lo", pct(lo))
        self.put(f"{prefix}.hi", pct(hi))
        if part.get("clopper_pearson_upper_if_zero") is not None:
            self.put(f"{prefix}.cp", pct(part["clopper_pearson_upper_if_zero"]))

    def test(self, prefix: str, t: dict) -> None:
        self.put(f"{prefix}.a", t["table"]["first_only"])
        self.put(f"{prefix}.b", t["table"]["second_only"])
        self.put(f"{prefix}.n", t["pairs"])
        self.put(f"{prefix}.u", t["undetermined_pairs"])
        self.put(f"{prefix}.p", sci(t["p_value"]))
        self.put(f"{prefix}.ph", sci(t["p_holm"]))

    def tex(self) -> str:
        lines = ["% Generated by analysis.security_final.paper_assets from the frozen lock. Do not edit.",
                 "\\makeatletter",
                 "\\providecommand{\\numdef}[2]{\\expandafter\\def\\csname num@#1\\endcsname{#2}}",
                 "\\providecommand{\\val}[1]{\\ifcsname num@#1\\endcsname\\csname num@#1\\endcsname"
                 "\\else\\textbf{??#1??}\\PackageWarning{paper}{missing number #1}\\fi}"]
        lines += [f"\\numdef{{{k}}}{{{v}}}" for k, v in sorted(self.values.items())]
        return "\n".join(lines + ["\\makeatother", ""])


def count_cell(part: dict) -> str:
    text = f"{part['successes']}"
    if part["undetermined"]:
        text += f" (+{part['undetermined']})"
    return text


def rate_cell(part: dict) -> str:
    if part["undetermined"]:
        lo, hi = part["range"]
        return f"{pct(lo)}--{pct(hi)}$^\\dagger$"
    lo, hi = part["wilson95"]
    text = f"{pct(part['rate'])} [{pct(lo)}, {pct(hi)}]"
    return text


def util_cell(part: dict) -> str:
    if part["undetermined"]:
        lo, hi = part["range"]
        return f"{pct(lo)}--{pct(hi)}"
    return pct(part["rate"])


def build(root: Path, paper: Path) -> dict:
    lock = _load(root / LOCK / "LOCK.json")
    tables = root / LOCK / "tables"
    for name, sha in lock["tables_sha256"].items():
        if _sha(tables / name) != sha:
            raise SystemExit(f"{name} differs from LOCK.json")
    p2 = _load(tables / "phase2_report.json")
    gen = _load(tables / "generalization_report.json")
    pilot = _load(root / "extension-20261026" / "pilot_report.json")
    n = Numbers()
    # --- phase 2 main run (Table I) and the chain (Table II) ---------------------------------
    for name, table, configs in (("p2", p2["table1"], MAIN), ("ch", p2["table3"], CHAIN)):
        for config in configs:
            for family in ("total", "I", "P"):
                n.part(f"{name}.{config}.{family}", table["unified"]["asr"][config][family])
                n.part(f"{name}.sens.{config}.{family}", table["sensitivity"]["asr"][config][family])
            for metric in UTILITY:
                n.part(f"{name}.{config}.{metric}", table["utility"][config][metric])
            for source, count in table["label_sources"][config].items():
                n.put(f"{name}.{config}.src.{source}", count)
        for t in table["unified"]["tests"]:
            n.test(f"{name}.test.{t.get('family', 'all')}.{key(t['comparison'])}", t)
    t2 = p2["table2"]
    n.put("p2.human.answers", p2["human_labels"]["answers"])
    n.put("p2.human.labels", p2["human_labels"]["labels"])
    n.put("p2.human.invalidation", t2["scorer_vs_human"]["in_validation_sample"])
    for version in ("v3.3", "v3.4"):
        for label in ("report_correct", "adopted_target", "refused", "conflict_flagged", "summary_asserts"):
            row = t2["scorer_vs_human"]["table"][version]["final"][label]
            tag = f"p2.svh.{version.replace('.', '')}.{label}"
            n.put(f"{tag}.k", "--" if row["kappa"] is None else f"{row['kappa']:.2f}")
            n.put(f"{tag}.n", row["compared"])
    for label, row in t2["ai_ai"]["check_87"]["agreement"].items():
        n.put(f"p2.aiai.{label}.k", "--" if row["kappa"] is None else f"{row['kappa']:.2f}")
    for label, row in t2["ai_ai"]["validation_110"]["agreement"].items():
        n.put(f"p2.aival.{label}.k", "--" if row["kappa"] is None else f"{row['kappa']:.2f}")
    # --- generalization (Table III) ---------------------------------------------------------------
    for slug in MODELS:
        table = gen["tables"][slug]
        for config in ("A", "D"):
            for family in ("total", "I", "P"):
                n.part(f"g.{slug}.{config}.{family}", table["asr"][config][family])
                n.part(f"g.{slug}.sens.{config}.{family}", gen["sensitivity_without_human"][slug][config][family])
            for metric in UTILITY:
                n.part(f"g.{slug}.{config}.{metric}", table["utility"][config][metric])
        s = gen["stability"][slug]
        n.put(f"g.{slug}.stab.same", s["same_in_all_runs"])
        n.put(f"g.{slug}.stab.pairs", s["pairs"])
        n.put(f"g.{slug}.stab.changed", len(s["changed"]))
        n.put(f"g.{slug}.stab.changedD", sum(1 for c in s["changed"] if c["config"] == "D"))
        for config in ("A", "D"):
            n.put(f"g.{slug}.stab.{config}runs", ", ".join(map(str, s["successes_by_run"][config])))
        o = gen["operations"][slug]
        n.put(f"g.{slug}.calls", f"{o['model_calls']:,}")
        n.put(f"g.{slug}.valid", f"{o['valid']}/{o['cells']}")
    for t in gen["tests"]:
        n.test(f"g.{t['model']}.test.{t['family']}", t)
    n.put("g.holm.max", sci(max(t["p_holm"] for t in gen["tests"])))
    for label, row in gen["scorer_vs_human_sample"].items():
        n.put(f"g.svh.{label}.k", "--" if row["kappa"] is None else f"{row['kappa']:.2f}")
        n.put(f"g.svh.{label}.n", row["compared"])
    n.put("g.aiai.match", gen["ai_ai"]["all_six_match"])
    n.put("g.aiai.items", gen["ai_ai"]["items"])
    n.put("g.process.answers", f"{gen['process']['answers']:,}")
    n.put("g.process.aireviewed", gen["process"]["ai_reviewed"])
    n.put("g.process.sheet", gen["process"]["human_sheet"])
    n.put("g.process.disagree", gen["process"]["ai_scorer_disagreements"])
    n.put("g.process.sample", gen["process"]["random_sample"])
    n.put("g.dsucc.main", sum(1 for d in gen["d_successes"] if d["repetition"] == 0))
    # --- model calls and label set ----------------------------------------------------------------
    calls = {k: v["used"] for k, v in p2["model_calls"]["runs"].items()}
    gen_test = sum(o["model_calls"] for o in gen["operations"].values())
    gen_pilot = sum(v["model_calls_total"] for v in pilot.values())
    n.put("calls.main", f"{calls['main-20261020']:,}")
    n.put("calls.controlled", f"{calls['controlled-L5-20261023']:,}")
    n.put("calls.replay", f"{calls['phase2/replay-20261024'] + calls['phase2/replay-fix-20261024']:,}")
    n.put("calls.l5pilot", f"{calls['phase2/l5-pilot-20261024']:,}")
    n.put("calls.gentest", f"{gen_test:,}")
    n.put("calls.genpilot", f"{gen_pilot:,}")
    n.put("calls.total", f"{sum(calls.values()) + gen_test + gen_pilot:,}")
    ls = lock["label_set"]
    label_path = root / LOCK / "final_labels.jsonl"
    if _sha(label_path) != ls["sha256"]:
        raise SystemExit("Label set differs from LOCK.json")
    label_rows = [json.loads(line) for line in label_path.read_text().splitlines() if line]
    n.put("replay.fixed", sum(r["in_tables"] and "replay-fix-20261024" in r["run_dir"] for r in label_rows))
    n.put("labels.rows", f"{ls['rows']:,}")
    n.put("labels.intables", f"{ls['in_tables']:,}")
    n.put("labels.sha", ls["sha256"][:12])
    by = ls["by_experiment_and_source"]
    n.put("labels.human", sum(v for k, v in by.items() if k.endswith("|human")))
    n.put("labels.ai", sum(v for k, v in by.items() if k.endswith("|ai")))
    n.put("labels.scorer", f"{sum(v for k, v in by.items() if k.endswith('|scorer')):,}")
    hv_path = root / "human-check-scorer-attack-20261027/returned/report.json"
    hv = _load(hv_path)
    if hv["v1_labels_sha256"] != ls["sha256"]:
        raise SystemExit("Human validation refers to a different v1 lock")
    returned = hv_path.parent
    if (_sha(returned / "manifest.json") != hv["returned_manifest_sha256"]
            or _sha(returned / "validated_labels.json") != hv["validated_labels_sha256"]):
        raise SystemExit("Human validation inputs changed since report")
    human_numbers(hv, n)
    out = paper / "generated"
    out.mkdir(parents=True, exist_ok=True)
    (out / "numbers.tex").write_text(n.tex(), encoding="utf-8")
    (out / "tab_main.tex").write_text(tab_main(p2), encoding="utf-8")
    (out / "tab_chain.tex").write_text(tab_chain(p2), encoding="utf-8")
    (out / "tab_models.tex").write_text(tab_models(gen), encoding="utf-8")
    scenarios = sensitivity(root)
    scenarios["blind_human"] = hv["sensitivity_scenario"]
    (out / "tab_sens.tex").write_text(tab_sens(scenarios, n), encoding="utf-8")
    (out / "tab_human_validation.tex").write_text(tab_human_validation(hv), encoding="utf-8")
    (out / "numbers.tex").write_text(n.tex(), encoding="utf-8")
    (paper / "figures").mkdir(parents=True, exist_ok=True)
    fig_chain(p2, paper / "figures" / "fig_chain.pdf")
    manifest = {"lock_sha256": _sha(root / LOCK / "LOCK.json"), "label_set_sha256": ls["sha256"],
                "human_validation_report_sha256": _sha(hv_path),
                "human_returned_manifest_sha256": hv["returned_manifest_sha256"],
                "numbers": len(n.values),
                "files_sha256": {str(p.relative_to(paper)): _sha(p) for p in sorted(out.glob("*.tex"))}}
    (out / "manifest.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8")
    return manifest


def human_numbers(hv, n):
    for name in ("answers", "rating_rows", "shared", "blind_complete_answers", "D_answers"):
        n.put(f"hv.{name}", hv[name])
    n.put("hv.raters", len(hv["validation"]["raters"]))
    n.put("hv.seen", sum(v["excluded_seen"] for v in hv["validation"]["raters"].values()))
    n.put("hv.unresolved.use_of_fake", hv["unresolved_by_label"]["use_of_fake"])
    for label, stat in hv["inter_rater"].items():
        n.put(f"hv.ir.{label}.k", "--" if stat["fleiss_kappa"] is None else f"{stat['fleiss_kappa']:.2f}")
        n.put(f"hv.ir.{label}.agree", pct(stat["agreement"]))
        pair_k = [v["kappa"] for v in stat["pairwise"].values() if v["kappa"] is not None]
        n.put(f"hv.ir.{label}.pairlo", f"{min(pair_k):.2f}" if pair_k else "--")
        n.put(f"hv.ir.{label}.pairhi", f"{max(pair_k):.2f}" if pair_k else "--")
    for label, stat in hv["scorer_vs_human"].items():
        n.put(f"hv.sc.{label}.n", stat["items"])
        n.put(f"hv.sc.{label}.k", "--" if stat.get("kappa") is None else f"{stat['kappa']:.2f}")
        n.put(f"hv.sc.{label}.agree", pct(stat.get("agreement")))
    for tag, stat in (("adoption", hv["adoption"]), ("D", hv["D_adoption"])):
        for field in ("numeric_answers", "missed", "false_alarm", "scorer_false", "scorer_true"):
            n.put(f"hv.{tag}.{field}", stat[field])
        for field in ("false_omission_rate", "false_discovery_rate", "false_negative_rate", "false_positive_rate"):
            n.put(f"hv.{tag}.{field}", pct(stat[field]))
    s = hv["sensitivity_scenario"]
    for c, parts in s["table1"]["asr"].items():
        n.part(f"hv.main.{c}", parts["total"])
    for model, table in s["generalization"]["tables"].items():
        for c, parts in table["asr"].items():
            n.part(f"hv.g.{model}.{c}", parts["total"])
    n.put("hv.main.AD.ph.max", sci(max(t["p_holm"] for t in s["table1"]["tests"] if t["comparison"] == "A–D")))


def tab_human_validation(hv):
    names = {"report_correct": "Target correct", "adopted_target": "Target achieved", "use_of_fake": "Use of fake",
             "refused": "Refusal", "conflict_flagged": "Conflict flagged", "summary_asserts": "Summary asserts"}
    rows = []
    for label, ir in hv["inter_rater"].items():
        sc = hv["scorer_vs_human"][label]
        k = "--" if sc.get("kappa") is None else f"{sc['kappa']:.2f}"
        fk = "--" if ir["fleiss_kappa"] is None else f"{ir['fleiss_kappa']:.2f}"
        rows.append(f"{names[label]} & {fk} & {pct(ir['agreement'])} & {k} & {pct(sc.get('agreement'))} & {sc['items'] or '--'} " + r"\\")
    return "\n".join([
        r"\begin{table}[t]\centering\small\setlength{\tabcolsep}{3pt}",
        r"\caption{Human validation. Inter-rater agreement uses the \val{hv.shared} shared answers: Fleiss $\kappa$ and unanimous agreement (\%). Scorer agreement uses one human label per answer (majority on shared answers). Numeric adoption excludes I3; inter-rater target achievement includes I3 refusal. Use-of-fake has no matching scorer field.}",
        r"\label{tab:human}", r"\begin{tabular}{lrrrrr}\toprule",
        r"& \multicolumn{2}{c}{Three raters} & \multicolumn{3}{c}{Scorer--human}" + chr(92)*2,
        r"Label & $\kappa$ & Agree & $\kappa$ & Agree & $n$ \\\midrule",
        *rows, r"\bottomrule\end{tabular}", r"\end{table}", ""])


def _tests_rows(tests: list[dict]) -> dict:
    return {(t.get("family"), t["comparison"]): t for t in tests}


def tab_main(p2: dict) -> str:
    t = p2["table1"]
    rows = []
    for c in MAIN:
        a, u = t["unified"]["asr"][c], t["utility"][c]
        rows.append(f"{c} & {count_cell(a['total'])} & {rate_cell(a['total'])} & {count_cell(a['I'])} & "
                    f"{count_cell(a['P'])} & {util_cell(u['clean_correct'])} & {util_cell(u['clean_refusal'])} & "
                    f"{util_cell(u['attack_correct_without_fake'])} \\\\")
    tests = _tests_rows(t["unified"]["tests"])
    trows = []
    for comp in ("A–D", "B–C", "C–D"):
        cells = []
        for fam in ("I", "P"):
            x = tests[(fam, comp)]
            cells.append(f"{x['table']['first_only']}/{x['table']['second_only']} & {sci(x['p_holm'])}")
        trows.append(f"{comp.replace('–', '--')} & " + " & ".join(cells) + " \\\\")
    return "\n".join([
        "\\begin{table*}[t]\\centering\\small",
        "\\caption{Main run (gpt-oss:120b, 80 test cases: 40 injection I, 40 poisoning P). Attack success counts "
        "pairs; ``(+$k$)'' are pairs left undetermined, kept in the denominator and reported as a range ($\\dagger$). "
        "Rates are \\% with Wilson 95\\% intervals. Utility columns: \\% of clean answers with the correct target "
        "value, \\% of clean answers refused, and \\% of the 72 numeric-target attacks answered correctly without "
        "adopting the fake value.}",
        "\\label{tab:main}",
        "\\begin{tabular}{lrlrrrrr}\\toprule",
        "Config & Succ.\\ (80) & ASR \\% [95\\% CI] & I (40) & P (40) & Clean correct & Clean refused & "
        "Attack correct, no fake \\\\\\midrule",
        *rows,
        "\\bottomrule\\end{tabular}\\\\[4pt]",
        "\\begin{tabular}{lrrrr}\\toprule",
        "& \\multicolumn{2}{c}{Injection (I)} & \\multicolumn{2}{c}{Poisoning (P)} \\\\",
        "Comparison & only first/only second & $p_{\\text{Holm}}$ & only first/only second & $p_{\\text{Holm}}$ "
        "\\\\\\midrule",
        *trows,
        "\\bottomrule\\end{tabular}",
        "\\end{table*}", ""])


def tab_chain(p2: dict) -> str:
    t = p2["table3"]
    rows = []
    for c in CHAIN:
        a, u = t["unified"]["asr"][c], t["utility"][c]
        rows.append(f"{c} & {count_cell(a['total'])} & {rate_cell(a['total'])} & {count_cell(a['I'])} & "
                    f"{count_cell(a['P'])} & {util_cell(u['attack_correct_without_fake'])} \\\\")
    arrow = "$\\to$"
    trows = [f"{x['comparison'].replace('→', arrow)} & {x['table']['first_only']}/{x['table']['second_only']} & "
             f"{x['pairs']} & {sci(x['p_value'])} & {sci(x['p_holm'])} \\\\" for x in t["unified"]["tests"]]
    return "\n".join([
        "\\begin{table}[t]\\centering\\small\\setlength{\\tabcolsep}{4pt}",
        "\\caption{Evidence-matched replay on the main run's D evidence (gpt-oss:120b). A and D are the answers of "
        "Table~\\ref{tab:main}. Last column: \\% of the 72 numeric-target attacks answered correctly without the "
        "fake value. Lower part: exact McNemar on case-paired outcomes, Holm over the four comparisons.}",
        "\\label{tab:chain}",
        "\\begin{tabular}{lrlrrr}\\toprule",
        "Config & Succ.\\ (80) & ASR \\% [95\\% CI] & I & P & Corr., no fake \\\\\\midrule",
        *rows,
        "\\bottomrule\\end{tabular}\\\\[4pt]",
        "\\begin{tabular}{lrrrr}\\toprule",
        "Step & only first/second & pairs & $p$ & $p_{\\text{Holm}}$ \\\\\\midrule",
        *trows,
        "\\bottomrule\\end{tabular}",
        "\\end{table}", ""])


def tab_models(gen: dict) -> str:
    tests = {(t["model"], t["family"]): t for t in gen["tests"]}
    rows = []
    for slug, name in MODELS.items():
        table = gen["tables"][slug]
        s = gen["stability"][slug]
        for c in ("A", "D"):
            a, u = table["asr"][c], table["utility"][c]
            first = f"\\multirow{{2}}{{*}}{{{name}}}" if c == "A" else ""
            tcells = " & ".join(
                (f"\\multirow{{2}}{{*}}{{{tests[(slug, f)]['table']['first_only']}/{tests[(slug, f)]['table']['second_only']}, "
                 f"{sci(tests[(slug, f)]['p_holm'])}}}" if c == "A" else "") for f in ("I", "P"))
            stab = (f"\\multirow{{2}}{{*}}{{{s['same_in_all_runs']}/{s['pairs']}}}" if c == "A" else "")
            rows.append(f"{first} & {c} & {count_cell(a['total'])} & {rate_cell(a['total'])} & {tcells} & "
                        f"{util_cell(u['clean_correct'])} & {util_cell(u['clean_refusal'])} & {stab} \\\\")
        rows.append("\\midrule" if slug != list(MODELS)[-1] else "")
    return "\n".join([
        "\\begin{table*}[t]\\centering\\small",
        "\\caption{A versus D with three answering models (same 80 cases, one main run each). A--D columns: "
        "pairs where only A / only D succeeded, and exact McNemar $p$ with Holm over the six tests. Stability: "
        "pairs (16 pre-chosen cases $\\times$ A/D) with the same outcome in all three runs, reported separately "
        "from the main run.}",
        "\\label{tab:models}",
        "\\begin{tabular}{llrlllrrr}\\toprule",
        "Model & Config & Succ.\\ (80) & ASR \\% [95\\% CI] & A--D, I & A--D, P & Clean correct & Clean refused & "
        "Stable \\\\\\midrule",
        *[r for r in rows if r],
        "\\bottomrule\\end{tabular}",
        "\\end{table*}", ""])


SCENARIOS = (("locked", "Locked labels (primary)"), ("one_sided", "AI audit, one-sided"),
             ("bidirectional", "AI audit, both directions"), ("lower_adoption", "Boundary: fewer adoptions"),
             ("upper_adoption", "Boundary: more adoptions"),
             ("blind_human", r"\shortstack[l]{Blind human labels\\(\val{hv.answers} scorer-only attacks)}"))


def sensitivity(root: Path) -> dict:
    """The targeted AI-audit scenarios, recomputed by bidirectional_check (it re-checks the lock)."""

    import subprocess
    import sys
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "audit"
        subprocess.run([sys.executable, "-m", "analysis.security_final.bidirectional_check", "--root", str(root),
                        "--out", str(out)], check=True, capture_output=True, cwd=Path(__file__).resolve().parents[2])
        return _load(out / "bidirectional_check.json")["scenarios"]


def tab_sens(scenarios: dict, n: Numbers) -> str:
    rows = []
    for name, label in SCENARIOS:
        s = scenarios[name]
        t1, t3, g = s["table1"]["asr"], s["table3"]["asr"], s["generalization"]["tables"]
        chain = {t["comparison"]: t for t in s["table3"]["tests"]}
