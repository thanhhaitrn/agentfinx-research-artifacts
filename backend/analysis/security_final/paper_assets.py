def fig_chain(p2: dict, path: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    asr = p2["table3"]["unified"]["asr"]
    tests = {t["comparison"]: t for t in p2["table3"]["unified"]["tests"]}
    fig, ax = plt.subplots(figsize=(3.4, 2.3))
    xs = range(len(CHAIN))
    for x, c in zip(xs, CHAIN, strict=True):
        part = asr[c]["total"]
        if part["undetermined"]:
            lo, hi = part["range"]
            mid = (lo + hi) / 2
            ax.bar(x, 100 * lo, color="#4c72b0", width=0.6)
            ax.bar(x, 100 * (hi - lo), bottom=100 * lo, color="#4c72b0", alpha=0.35, width=0.6, hatch="///")
            label = f"{part['successes']}(+{part['undetermined']})"
            top = 100 * hi
        else:
            mid = part["rate"]
            lo, hi = part["wilson95"]
            ax.bar(x, 100 * mid, color="#4c72b0", width=0.6)
            ax.errorbar(x, 100 * mid, yerr=[[100 * (mid - lo)], [100 * (hi - mid)]], color="black", capsize=2, lw=0.8)
            label = f"{part['successes']}"
            top = 100 * hi
        ax.text(x, top + 1.5, label, ha="center", va="bottom", fontsize=7)
    for i, comp in enumerate(("A→Apre", "Apre→Apost", "Apost→ApostG")):
        t = tests[comp]
        left, right = CHAIN.index(comp.split("→")[0]), CHAIN.index(comp.split("→")[1])
        y = 62 + 6 * (i % 2)
        ax.annotate("", xy=(right, y), xytext=(left, y), arrowprops=dict(arrowstyle="->", lw=0.7))
        star = "$p_{\\rm Holm}$=" + (f"{t['p_holm']:.3g}" if t["p_holm"] >= 0.001 else f"{t['p_holm']:.1e}")
        ax.text((left + right) / 2, y + 0.8, star, ha="center", va="bottom", fontsize=6)
    t = tests["Apost→D"]
    ax.annotate("", xy=(4, 48), xytext=(2, 48), arrowprops=dict(arrowstyle="->", lw=0.7, ls="--"))
    ax.text(3, 48.8, f"$p_{{\\rm Holm}}$={t['p_holm']:.3g}", ha="center", va="bottom", fontsize=6)
    ax.set_xticks(list(xs), CHAIN, fontsize=8)
    ax.set_ylabel("Attack success (%)", fontsize=8)
    ax.set_ylim(0, 75)
    ax.tick_params(axis="y", labelsize=7)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    fig.tight_layout()
    fig.savefig(path, metadata={"CreationDate": None, "ModDate": None})
    plt.close(fig)


